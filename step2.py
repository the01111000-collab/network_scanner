# ===== ขั้นที่ 2: ลอง ping เครื่องเดียว ว่าเปิดอยู่ไหม =====

import subprocess                       # เครื่องมือสั่งรันคำสั่งของ Windows (เช่น ping) จาก Python
target = "192.168.1.1"  #"192.168.1.1"  # เครื่องเป้าหมายที่จะเช็ค (192.168.1.1 มักเป็นเราเตอร์)
                        #"192.168.1.222" # ตัวอย่าง IP ที่น่าจะไม่มีเครื่องอยู่ ไว้ลองเทียบผล
                        #"10.255.255.1"  # ตัวอย่าง IP นอกวงบ้าน ไว้ลองดูว่าผลเป็นยังไง
# สั่ง ping 1 ครั้ง แล้วเก็บข้อความผลลัพธ์ไว้ในตัวแปร result (เป็นตัวหนังสือ ไม่โชว์บนจอ)
result = subprocess.run(["ping", "-n", "1", target], capture_output=True, text=True)


# บรรทัดทดลองที่ปิดไว้ ใช้ส่องดูผลลัพธ์ตอนเรียนรู้:
 #print(result.stdout)                  # ดูข้อความผลลัพธ์ทั้งหมดของ ping
 #print(result.returncode)              # ดูรหัสผล (0 = สำเร็จ)
 #print("bytes" in result.stdout)       # เช็คว่ามีคำว่า bytes ไหม
 #print("time" in result.stdout)        # เช็คว่ามีคำว่า time ไหม
 #print("TTL" in result.stdout)         # เช็คว่ามีคำว่า TTL ไหม (สุดท้ายเลือกใช้ตัวนี้)


if "TTL" in result.stdout:              # ถ้ามีคำว่า TTL แปลว่าเครื่องตอบกลับมา
    print("Online", target)             # แสดงว่าเครื่องออนไลน์
else:                                   # ถ้าไม่มี แปลว่าเครื่องไม่ตอบ
    print("Offline", target)            # แสดงว่าเครื่องออฟไลน์
