# ===== ทดลองการจับเวลา =====

import time                             # เครื่องมือเกี่ยวกับเวลา

start_time = time.time()                # จดเวลาตอนนี้ (เป็นตัวเลขวินาทีนับจากปี 1970)
time.sleep(2)                           # สั่งให้โปรแกรมหยุดรอเฉยๆ 2 วินาที
end_time = time.time()                  # จดเวลาอีกครั้งหลังรอเสร็จ

print(start_time)                       # แสดงเวลาตอนเริ่ม (เป็นเลขยาวๆ)
print(end_time)                         # แสดงเวลาตอนจบ
print(end_time - start_time)            # เอามาลบกัน = ระยะเวลาที่ผ่านไป (ควรได้ประมาณ 2)
