# ===== โปรแกรมสแกนเครือข่าย (ตัวหลัก) =====
# หน้าที่: ไล่เช็คทุกเครื่องในวง 192.168.1.1 - 192.168.1.254
# ว่าเครื่องไหนเปิดอยู่ แล้วเช็คต่อว่าเปิด "ประตู" (port) อะไรไว้บ้าง

import subprocess   # เครื่องมือสำหรับสั่งรันคำสั่งของ Windows (เช่น ping) จากใน Python
import socket       # เครื่องมือสำหรับเชื่อมต่อเครือข่าย ใช้ "เคาะประตู" port ของเครื่องอื่น
import time         # เครื่องมือเกี่ยวกับเวลา ใช้จับเวลาว่าสแกนนานแค่ไหน

prefix = "192.168.1."               # ส่วนหน้าของ IP ที่เหมือนกันทุกเครื่องในบ้าน เดี๋ยวจะเอาเลขท้ายมาต่อ
ports = [22, 53, 80, 443, 3389]     # รายการ port ที่จะเช็ค: 22=SSH, 53=DNS, 80=เว็บ, 443=เว็บแบบปลอดภัย, 3389=รีโมทเดสก์ท็อป
online_hosts = []                   # กล่องเปล่าไว้เก็บรายชื่อเครื่องที่เปิดอยู่
open_ports = []                     # กล่องเปล่าไว้เก็บคู่ (เครื่อง, port) ที่เปิดอยู่

time_start = time.time()            # กดนาฬิกาจับเวลา: จดเวลาตอนเริ่มสแกน

# ฟังก์ชันเช็คว่าเครื่องนี้ "เปิดอยู่ไหม" ด้วยการ ping
def is_online(target):
    # สั่ง ping ไปที่เครื่องเป้าหมาย 1 ครั้ง (-n 1) รอคำตอบไม่เกิน 500 มิลลิวินาที (-w 500)
    # capture_output=True คือเก็บข้อความผลลัพธ์ไว้ ไม่โชว์บนจอ / text=True คือให้ได้ผลเป็นตัวหนังสือ
    result = subprocess.run(["ping", "-n", "1", "-w", "500", target], capture_output = True, text = True)

    if "TTL" in result.stdout:      # ถ้าในข้อความตอบกลับมีคำว่า "TTL" แปลว่าเครื่องนั้นตอบกลับมาจริง
        return True                 # ตอบว่า "เปิดอยู่"
    else:                           # ถ้าไม่มีคำว่า TTL แปลว่าไม่มีใครตอบ
        return False                # ตอบว่า "ปิดอยู่ / ไม่มีเครื่องนี้"
# ฟังก์ชันเช็คว่า port นี้ของเครื่องนี้ "เปิดอยู่ไหม" (เหมือนเดินไปเคาะประตูบ้าน)
def is_port_open(ip, port):
    s = socket.socket()             # สร้างช่องทางเชื่อมต่อขึ้นมา 1 อัน (เหมือนหยิบโทรศัพท์ขึ้นมา)
    s.settimeout(0.5)               # ตั้งว่ารอได้แค่ครึ่งวินาที ถ้าไม่มีใครรับก็เลิกรอ
    result = s.connect_ex((ip, port))   # ลองต่อไปที่เครื่องและ port นั้น ได้ 0 = ต่อติด, เลขอื่น = ต่อไม่ติด
    s.close()                       # วางสาย ปิดการเชื่อมต่อ
    return result == 0              # ตอบ True ถ้าต่อติด (port เปิด), False ถ้าต่อไม่ติด (port ปิด)
# วนลูปเลข 1 ถึง 254 (range หยุดก่อน 255) เพื่อไล่เช็คทุกเครื่องในวง
for i in range(1, 255):
    target = f"{prefix}{i}"         # เอาส่วนหน้ามาต่อกับเลข เช่น "192.168.1." + 5 = "192.168.1.5"
    print(f"scanning {target} ...") # บอกบนจอว่ากำลังสแกนเครื่องไหน
    if is_online(target):           # ถามฟังก์ชันด้านบนว่าเครื่องนี้เปิดอยู่ไหม
        print(f"{target} is online")    # ถ้าเปิด บอกบนจอว่าออนไลน์
        online_hosts.append(target)     # จดชื่อเครื่องนี้ลงกล่องเครื่องที่เปิดอยู่
        for port in ports:              # ไล่เช็ค port ทีละตัวในรายการ
            result = is_port_open(target, port)     # ลองเคาะประตู port นี้
            if result:                              # ถ้าประตูเปิด
                print(f"port {port} is open")       # บอกบนจอว่า port เปิด
                open_ports.append((target, port))   # จดคู่ (เครื่อง, port) ลงกล่อง
            else:                                   # ถ้าประตูปิด
                print(f"port {port} is closed")     # บอกบนจอว่า port ปิด
    else:                           # ถ้าเครื่องนี้ไม่ตอบ ping
        print(f"{target} is offline")   # บอกบนจอว่าออฟไลน์ แล้วข้ามไปเครื่องถัดไป




end_time = time.time()              # สแกนครบแล้ว จดเวลาตอนจบ

print("===== Health Report =====")  # พิมพ์หัวข้อรายงานสรุป

print(f"scan finished in {round(end_time - time_start, 2)} seconds")   # เวลาจบ - เวลาเริ่ม = ใช้เวลากี่วินาที (ปัดเหลือทศนิยม 2 ตำแหน่ง)
print(f"online hosts: {len(online_hosts)}: {online_hosts}")            # บอกว่าเจอเครื่องเปิดอยู่กี่เครื่อง และมีเครื่องไหนบ้าง
print(f"open ports: {len(open_ports)}: {open_ports}")                  # บอกว่าเจอ port เปิดกี่อัน และอยู่ที่เครื่องไหน port อะไร
